"""Emit a tiny ctypes Python wrapper for a generated solver.

The wrapper mirrors the C ABI structs exactly (so ``FomWorkspace`` has the same
layout as the emitted header) and exposes an OSQP-like ``Solver`` class:

    from fom_solver import Solver
    solver = Solver()                 # loads libfomsolver.{so,dylib}
    out = solver.solve(p0=my_param)   # -> {"x", "iter", "residual", "status"}
    solver.update_settings(tol=1e-6, check_termination=10)  # runtime FomSettings
"""

from __future__ import annotations

from pathlib import Path

from fomtools.codegen.config import CodegenConfig
from fomtools.codegen.ir import FomIR


def emit_wrapper(ir: FomIR, out_dir: str | Path, config: CodegenConfig) -> Path:
    """Write ``python/fom_solver.py`` (+ ``__init__.py``). Returns the module path."""
    out = Path(out_dir) / "python"
    out.mkdir(parents=True, exist_ok=True)
    (out / "__init__.py").write_text("from .fom_solver import Solver\n\n__all__ = ['Solver']\n")
    module = out / "fom_solver.py"
    module.write_text(_render(ir, config))
    return module


def _render(ir: FomIR, config: CodegenConfig) -> str:
    ctype = "ctypes.c_double" if config.dtype == "float64" else "ctypes.c_float"
    state_dim = ir.state_dim
    max_vec = ir.max_rhs_dim

    param_fields = (
        "\n".join(f'        ("{p.name}", fom_float * {p.dim}),' for p in ir.params)
        or '        ("_unused", ctypes.c_int),'
    )

    tmp_fields = "\n".join(f'        ("{s.name}", fom_float * {s.out_dim}),' for s in ir.body)

    param_names = [p.name for p in ir.params]
    param_dims = {p.name: p.dim for p in ir.params}

    return f'''"""Auto-generated ctypes wrapper for the `{ir.name}` solver.

Do not edit by hand: regenerated by fomtools.codegen.
"""

import ctypes
import sys
from pathlib import Path

import numpy as np

fom_float = {ctype}

STATE_DIM = {state_dim}
PARAM_NAMES = {param_names!r}
PARAM_DIMS = {param_dims!r}


class FomSettings(ctypes.Structure):
    _fields_ = [
        ("max_iter", ctypes.c_int),
        ("tol", fom_float),
        ("check_termination", ctypes.c_int),
    ]


class FomParams(ctypes.Structure):
    _fields_ = [
{param_fields}
    ]


class FomSolution(ctypes.Structure):
    _fields_ = [
        ("x", fom_float * STATE_DIM),
        ("iter", ctypes.c_int),
        ("residual", fom_float),
        ("status", ctypes.c_int),
    ]


class FomWorkspace(ctypes.Structure):
    _fields_ = [
        ("settings", FomSettings),
        ("params", FomParams),
        ("solution", FomSolution),
        ("state", fom_float * {state_dim}),
        ("new_state", fom_float * {state_dim}),
        ("acc", fom_float * {max_vec}),
{tmp_fields}
    ]


def _default_lib_path():
    base = Path(__file__).resolve().parent.parent
    names = ["libfomsolver.dylib", "libfomsolver.so"] if sys.platform == "darwin" else [
        "libfomsolver.so",
        "libfomsolver.dylib",
    ]
    for name in names:
        cand = base / name
        if cand.exists():
            return str(cand)
    return str(base / names[0])


class Solver:
    """Thin handle around the generated C solver."""

    def __init__(self, lib_path=None):
        self._lib = ctypes.CDLL(lib_path or _default_lib_path())
        self._lib.fom_set_default_settings.argtypes = [ctypes.POINTER(FomSettings)]
        self._lib.fom_setup.argtypes = [ctypes.POINTER(FomWorkspace), ctypes.POINTER(FomSettings)]
        self._lib.fom_update_params.argtypes = [
            ctypes.POINTER(FomWorkspace), ctypes.POINTER(FomParams)
        ]
        self._lib.fom_solve.argtypes = [ctypes.POINTER(FomWorkspace)]
        self._lib.fom_solve.restype = ctypes.c_int
        self._lib.fom_cleanup.argtypes = [ctypes.POINTER(FomWorkspace)]

        self._work = FomWorkspace()
        self._settings = FomSettings()
        self._lib.fom_set_default_settings(ctypes.byref(self._settings))
        self._lib.fom_setup(ctypes.byref(self._work), ctypes.byref(self._settings))

    def update_settings(self, **settings):
        """Change runtime settings (``max_iter``, ``tol``, ``check_termination``)."""
        for name, value in settings.items():
            if name not in ("max_iter", "tol", "check_termination"):
                raise ValueError(f"unknown setting {{name!r}}")
            setattr(self._settings, name, value)
        self._lib.fom_setup(ctypes.byref(self._work), ctypes.byref(self._settings))

    def solve(self, **params):
        """Solve for the given parameters. Returns a result dict."""
        p = FomParams()
        for name in PARAM_NAMES:
            if name not in params:
                raise ValueError(f"missing parameter {{name!r}}")
            vec = np.ascontiguousarray(params[name], dtype=np.float64).reshape(-1)
            if vec.size != PARAM_DIMS[name]:
                raise ValueError(
                    f"parameter {{name!r}} expects {{PARAM_DIMS[name]}} entries, got {{vec.size}}"
                )
            arr = getattr(p, name)
            for i in range(vec.size):
                arr[i] = vec[i]
        self._lib.fom_update_params(ctypes.byref(self._work), ctypes.byref(p))
        status = self._lib.fom_solve(ctypes.byref(self._work))
        sol = self._work.solution
        return {{
            "x": np.array([sol.x[i] for i in range(STATE_DIM)]),
            "iter": int(sol.iter),
            "residual": float(sol.residual),
            "status": int(status),
        }}

    def __del__(self):
        try:
            self._lib.fom_cleanup(ctypes.byref(self._work))
        except Exception:
            pass
'''
