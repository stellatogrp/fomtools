"""C bridge between cvxpygen's canonicalization code and the fomtools solver.

cvxpygen's generated ``cpg_solve()`` refreshes the canonical parameters
(``Canon_Params``) from user parameter updates and then invokes the solver via
``solve_function_call``. The bridge emitted here provides that entry point:
it copies the canonical vectors into the fomtools ``FomParams`` struct, runs
``fom_solve``, and exposes the solution and solver info through the global
symbols that cvxpygen's retrieval code reads (``sol_x``, ``sol_y``,
``fom_obj_val``, ...).

Everything is statically allocated, matching
``ws_statically_allocated_in_solver_code = True`` on the interface.
"""

from __future__ import annotations

from pathlib import Path

from fomtools.cvxpygen.builders import FomSpec
from fomtools.cvxpygen.qpdata import QPData

def _piece_dims(qp: QPData) -> dict[str, tuple[str, int, int]]:
    """Map each canonical piece to (Canon_Params member, offset, length)."""
    return {
        "q": ("q", 0, qp.n),
        "b": ("l", 0, qp.n_eq),
        "u_ineq": ("u", qp.n_eq, qp.n_ineq),
    }


def emit_bridge(
    spec: FomSpec,
    qp: QPData,
    solver_code_dir: str | Path,
    prefix: str,
    has_quad_term: bool,
) -> None:
    """Write ``include/cpg_fom_bridge.h`` and ``src/cpg_fom_bridge.c``.

    ``prefix`` is cvxpygen's (already normalized) symbol prefix; it applies to
    the solve entry point and the generated ``Canon_Params``/``Canon_Settings``
    structs. The solution/info globals are unprefixed, mirroring cvxpygen's
    own OSQP backend (one solver instance per binary).
    """
    solver_code_dir = Path(solver_code_dir)
    n, m = qp.n, qp.m
    fn = f"{prefix}cpg_fom_solve"

    header = f"""\
/* Bridge between CVXPYgen canonicalization code and the fomtools solver.
 * Auto-generated by fomtools.cvxpygen — do not edit. */
#ifndef CPG_FOM_BRIDGE_H
#define CPG_FOM_BRIDGE_H

#ifdef __cplusplus
extern "C" {{
#endif

/* Canonical primal and dual solution (read by cpg_retrieve_*). */
extern double sol_x[{n}];
extern double sol_y[{m}];

/* Solver info (read by cpg_retrieve_info). The residual is the fomtools
 * termination metric ||x_k - x_(k-1)||_inf, reported as both residuals. */
extern double fom_obj_val;
extern int fom_iter;
extern int fom_status;
extern double fom_pri_res;
extern double fom_dua_res;

/* Refresh parameters from Canon_Params, solve, and publish the solution. */
extern void {fn}(void);

#ifdef __cplusplus
}}
#endif

#endif /* CPG_FOM_BRIDGE_H */
"""

    copies = []
    dims = _piece_dims(qp)
    for i, piece in enumerate(spec.param_copy):
        member, offset, length = dims[piece]
        src = f"{prefix}Canon_Params.{member}" + (f" + {offset}" if offset else "")
        copies.append(
            f"  for (i = 0; i < {length}; i++) {{\n"
            f"    fom_params.p{i}[i] = (fom_float)({src})[i];\n"
            f"  }}"
        )
    copies_src = "\n".join(copies)

    if has_quad_term:
        quad_src = f"""\
  for (i = 0; i < {n}; i++) {{
    for (j = {prefix}Canon_Params.P->p[i]; j < {prefix}Canon_Params.P->p[i + 1]; j++) {{
      fom_obj_val += 0.5 * {prefix}Canon_Params.P->x[j] * sol_x[{prefix}Canon_Params.P->i[j]] * sol_x[i];
    }}
  }}
"""
    else:
        quad_src = "  /* no quadratic term */\n"

    source = f"""\
/* Bridge between CVXPYgen canonicalization code and the fomtools solver.
 * Auto-generated by fomtools.cvxpygen — do not edit. */
#include "cpg_fom_bridge.h"
#include "cpg_workspace.h"
#include "fom_solver.h"

double sol_x[{n}];
double sol_y[{m}];
double fom_obj_val;
int fom_iter;
int fom_status;
double fom_pri_res;
double fom_dua_res;

static FomWorkspace fom_work;
static int fom_initialized = 0;

void {fn}(void) {{
  FomParams fom_params;
  int i;
{"  int j;" if has_quad_term else ""}
  if (!fom_initialized) {{
    FomSettings fom_settings;
    fom_set_default_settings(&fom_settings);
    fom_setup(&fom_work, &fom_settings);
    fom_initialized = 1;
  }}

  /* Runtime-tunable settings, kept in sync with cpg_set_solver_*. */
  fom_work.settings.max_iter = (fom_int){prefix}Canon_Settings.max_iter;
  fom_work.settings.tol = (fom_float){prefix}Canon_Settings.tol;

  /* Canonical parameter vectors -> FomParams (field order = p0, p1, ...). */
{copies_src}
  fom_update_params(&fom_work, &fom_params);

  fom_status = (int)fom_solve(&fom_work);

  for (i = 0; i < {n}; i++) {{
    sol_x[i] = (double)fom_work.solution.x[{spec.primal_offset} + i];
  }}
  for (i = 0; i < {m}; i++) {{
    sol_y[i] = (double)fom_work.solution.x[{spec.dual_offset} + i];
  }}
  fom_iter = (int)fom_work.solution.iter;
  fom_pri_res = (double)fom_work.solution.residual;
  fom_dua_res = (double)fom_work.solution.residual;

  /* Objective 0.5 x'Px + q'x; cvxpygen's retrieve_info adds the constant d
   * and flips the sign for maximization problems. */
  fom_obj_val = 0.0;
{quad_src}\
  for (i = 0; i < {n}; i++) {{
    fom_obj_val += {prefix}Canon_Params.q[i] * sol_x[i];
  }}
}}
"""

    (solver_code_dir / "include").mkdir(parents=True, exist_ok=True)
    (solver_code_dir / "src").mkdir(parents=True, exist_ok=True)
    (solver_code_dir / "include" / "cpg_fom_bridge.h").write_text(header)
    (solver_code_dir / "src" / "cpg_fom_bridge.c").write_text(source)


def write_solver_cmake_stub(solver_code_dir: str | Path) -> None:
    """Create ``solver_code/CMakeLists.txt`` for cvxpygen's writer to append to.

    The writer appends ``file(GLOB SOLVER_SRC ...)`` blocks built from the
    interface's ``cmake_sources``/``cmake_headers`` and exports them to the
    parent scope, so the stub itself carries no build logic.
    """
    path = Path(solver_code_dir) / "CMakeLists.txt"
    path.write_text(
        "# fomtools solver sources — populated by CVXPYgen (write_canon_cmake)\n"
    )
