"""C bridge between cvxpygen's canonicalization code and the fomtools solver.

cvxpygen's generated ``cpg_solve()`` refreshes the canonical parameters
(``Canon_Params``) from user parameter updates and then invokes the solver via
``solve_function_call``. The bridge emitted here provides that entry point:
it copies the canonical vectors into the fomtools ``FomParams`` struct, runs
``fom_solve``, and exposes the solution and solver info through the global
symbols that cvxpygen's retrieval code reads (``sol_x``, ``sol_y``,
``fom_obj_val``, ...).

Everything is statically allocated, matching
``ws_statically_allocated_in_solver_code = True`` on the interface.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from fomtools.cvxpygen.builders import BaseFomSpec
from fomtools.cvxpygen.qpdata import CVXPYGEN_INF, QPData
from fomtools.cvxpygen.scaling import Scaling

_BANNER = (
    "/* Bridge between CVXPYgen canonicalization code and the fomtools solver.\n"
    " * Auto-generated by fomtools.cvxpygen — do not edit. */"
)


def cmake_solver_sources(target) -> list[str]:
    """CMake source paths (cvxpygen ``solver_code`` scope) for one target.

    Mirrors the translation units the target actually scaffolds — the solver
    body, the numeric data, and the matrix-vector / linear-solve sources, which
    become ``.cu`` on the CUDA backend — plus the generated bridge. cvxpygen
    globs this list into its build, so the file extensions must match what the
    target's ``scaffold`` wrote (e.g. ``src/fom_ops.cu`` for CUDA, ``.c`` for
    embedded / OpenMP). The bridge stays host C on every backend: it only calls
    the (``extern "C"``) ABI and touches the host-side workspace arrays.
    """
    rel = [
        target.solver_source_path(),
        "src/fom_data.c",
        target.linsolve_source_path(),
        target.ops_source_path(),
        "src/cpg_fom_bridge.c",
    ]
    return [f"${{CMAKE_CURRENT_SOURCE_DIR}}/{r}" for r in rel]


#: Every runtime setting the bridge can forward, and the copy that does it.
#: Which of these actually exist is decided by the interface from the FOM's
#: declared kind — a solver that cannot honor a setting does not advertise it.
_SETTING_COPIES = {
    "max_iter": "  fom_work.settings.max_iter = (fom_int){p}Canon_Settings.max_iter;",
    "tol": "  fom_work.settings.tol = (fom_float){p}Canon_Settings.tol;",
    "check_termination": (
        "  fom_work.settings.check_termination = (fom_int){p}Canon_Settings.check_termination;"
    ),
}


def _settings_block(prefix: str, settings: tuple[str, ...], schedule_len: int | None) -> str:
    """The per-solve copy from cvxpygen's Canon_Settings into the FomWorkspace.

    ``settings`` names the members that exist; an empty tuple means cvxpygen
    emitted no ``Canon_Settings`` struct at all (an unrolled solver has no
    iteration count, tolerance or check interval to tune), so the bridge must
    not name it.

    ``schedule_len`` caps ``max_iter`` for a scheduled solver: past the end of a
    coefficient table the emitted accessor clamps to its last entry, which is
    memory-safe but freezes the coefficients instead of continuing the method.
    Capping here keeps a caller's ``cpg_set_solver_max_iter`` from quietly
    running a different algorithm.
    """
    if not settings:
        return (
            "  /* No runtime settings: this solver is an unrolled single pass, so\n"
            "   * there is no iteration count, tolerance or check interval to set. */"
        )
    lines = ["  /* Runtime-tunable settings, kept in sync with cpg_set_solver_*. */"]
    for name in settings:
        if name == "max_iter" and schedule_len is not None:
            lines += [
                f"  /* Capped at the {schedule_len}-entry schedule tables (FOM_MAX_ITER):",
                "   * past their end the emitted accessors clamp to the last value, which",
                "   * would freeze the coefficients instead of continuing the method. */",
                f"  fom_work.settings.max_iter = (fom_int)({prefix}Canon_Settings.max_iter < "
                f"{schedule_len} ? {prefix}Canon_Settings.max_iter : {schedule_len});",
            ]
        else:
            lines.append(_SETTING_COPIES[name].format(p=prefix))
    return "\n".join(lines)


def _piece_dims(qp: QPData) -> dict[str, tuple[str, int, int]]:
    """Map each canonical piece to (Canon_Params member, offset, length).

    The offset of a constraint piece is also its first row in the equilibration
    scaling ``E`` (equality rows first, then inequality rows), which
    :func:`_param_copy_line` relies on to index ``bridge_E``.
    """
    return {
        "q": ("q", 0, qp.n),
        "b": ("l", 0, qp.n_eq),
        "u_ineq": ("u", qp.n_eq, qp.n_ineq),
    }


def _c_array(name: str, values: np.ndarray) -> str:
    body = ", ".join(f"{float(v):.17g}" for v in values)
    return f"static const double {name}[{max(len(values), 1)}] = {{{body or '0'}}};"


def _scaling_block(scaling: Scaling) -> str:
    """Static scaling data: ``x = D x~``, rows scaled by ``E``, cost by ``c``."""
    return "\n".join(
        [
            "/* Ruiz equilibration of the canonical QP (fomtools.cvxpygen.scaling):",
            " * the solver iterates on c D P D, c D q, E A D, E l, E u. */",
            _c_array("bridge_D", scaling.D),
            _c_array("bridge_E", scaling.E),
            f"static const double bridge_c = {float(scaling.c):.17g};",
        ]
    )


def _param_copy_line(piece: str, index: int, src: str, offset: int, scaled: bool) -> str:
    """One element of a canonical piece into ``fom_params.p<index>``, scaled if equilibrated."""
    value = f"({src})[i]"
    if not scaled:
        rhs = value
    elif piece == "q":
        rhs = f"bridge_c * bridge_D[i] * {value}"
    else:
        # b and u_ineq rows; cvxpygen's +/-1e30 infinities stay infinite. The
        # Canon_Params offset doubles as the row offset into E (see _piece_dims).
        e = f"bridge_E[{offset} + i]" if offset else "bridge_E[i]"
        inf = f"{CVXPYGEN_INF:g}"
        rhs = f"(({value} >= {inf} || {value} <= -{inf}) ? {value} : {e} * {value})"
    return f"    fom_params.p{index}[i] = (fom_float)({rhs});"


def _residual_block(qp: QPData, prefix: str, has_quad_term: bool) -> str:
    """C code computing OSQP-style primal/dual residuals into the info globals.

    ``Canon_Params`` exposes the canonical ``P`` (``n x n`` symmetric, CSC) and
    ``A`` (``m x n``, CSC by variable columns) matrices plus the bound vectors
    ``l``/``u`` (length ``m``, infinities clamped to ``+/-1e30``). With the
    returned primal ``sol_x`` and dual ``sol_y`` this yields the same residuals
    OSQP reports — replacing the old behaviour where both residual fields were
    just the FOM's ``||x_k - x_(k-1)||_inf`` state-change metric.
    """
    p = prefix
    n, m = qp.n, qp.m
    lines: list[str] = []

    # Primal residual: ||Ax - clamp(Ax, l, u)||_inf == max(Ax - u, l - Ax, 0).
    if m > 0:
        lines += [
            f"  for (i = 0; i < {m}; i++) bridge_Ax[i] = 0.0;",
            f"  for (i = 0; i < {n}; i++) {{  /* A is {m}x{n}, CSC by variable column */",
            f"    for (j = {p}Canon_Params.A->p[i]; j < {p}Canon_Params.A->p[i + 1]; j++)",
            f"      bridge_Ax[{p}Canon_Params.A->i[j]] += {p}Canon_Params.A->x[j] * sol_x[i];",
            "  }",
            "  fom_pri_res = 0.0;",
            f"  for (i = 0; i < {m}; i++) {{",
            f"    double over = bridge_Ax[i] - {p}Canon_Params.u[i];",
            f"    double under = {p}Canon_Params.l[i] - bridge_Ax[i];",
            "    double viol = over > under ? over : under;",
            "    if (viol > fom_pri_res) fom_pri_res = viol;",
            "  }",
        ]
    else:
        lines.append("  fom_pri_res = 0.0;  /* no constraints */")

    # Dual residual: ||P x + q + A^T y||_inf.
    lines.append(f"  for (i = 0; i < {n}; i++) bridge_g[i] = {p}Canon_Params.q[i];")
    if has_quad_term:
        lines += [
            f"  for (i = 0; i < {n}; i++) {{  /* + P x (P is {n}x{n} symmetric, CSC) */",
            f"    for (j = {p}Canon_Params.P->p[i]; j < {p}Canon_Params.P->p[i + 1]; j++)",
            f"      bridge_g[{p}Canon_Params.P->i[j]] += {p}Canon_Params.P->x[j] * sol_x[i];",
            "  }",
        ]
    if m > 0:
        lines += [
            f"  for (i = 0; i < {n}; i++) {{  /* + A^T y */",
            f"    for (j = {p}Canon_Params.A->p[i]; j < {p}Canon_Params.A->p[i + 1]; j++)",
            f"      bridge_g[i] += {p}Canon_Params.A->x[j] * sol_y[{p}Canon_Params.A->i[j]];",
            "  }",
        ]
    lines += [
        "  fom_dua_res = 0.0;",
        f"  for (i = 0; i < {n}; i++) {{",
        "    double a = bridge_g[i] < 0.0 ? -bridge_g[i] : bridge_g[i];",
        "    if (a > fom_dua_res) fom_dua_res = a;",
        "  }",
    ]
    return "\n".join(lines)


def emit_bridge(
    spec: BaseFomSpec,
    qp: QPData,
    solver_code_dir: str | Path,
    prefix: str,
    has_quad_term: bool,
    settings: tuple[str, ...] = ("max_iter", "tol", "check_termination"),
    schedule_len: int | None = None,
    iter_count: int | None = None,
    scaling: Scaling | None = None,
) -> None:
    """Write ``include/cpg_fom_bridge.h`` and ``src/cpg_fom_bridge.c``.

    ``prefix`` is cvxpygen's (already normalized) symbol prefix; it applies to
    the solve entry point and the generated ``Canon_Params``/``Canon_Settings``
    structs. The solution/info globals are unprefixed, as in cvxpygen's
    statically-allocated solver backends (one solver instance per binary).

    ``settings`` names the ``Canon_Settings`` members to forward each solve; it
    must match what the interface put in its ``stgs``, since anything else names
    a struct member cvxpygen did not emit. ``schedule_len`` caps ``max_iter`` at
    the length of the coefficient tables. ``iter_count`` overrides the reported
    iteration count, which an unrolled solver needs: its loop runs once, so
    ``solution.iter`` is 1 rather than the number of iterations the emitted
    straight-line body actually performs.

    With ``scaling`` the solver was built on the equilibrated QP
    (:func:`fomtools.cvxpygen.scaling.scale_qp`): the parameters are scaled on
    the way in, the primal and dual solution unscaled on the way out
    (``x = D x~``, ``y = E y~ / c``), and the residuals and objective, which
    read the original ``Canon_Params``, are those of the original problem.
    """
    solver_code_dir = Path(solver_code_dir)
    n, m = qp.n, qp.m
    fn = f"{prefix}cpg_fom_solve"

    header = f"""\
{_BANNER}
#ifndef CPG_FOM_BRIDGE_H
#define CPG_FOM_BRIDGE_H

#ifdef __cplusplus
extern "C" {{
#endif

/* Canonical primal and dual solution (read by cpg_retrieve_*). */
extern double sol_x[{n}];
extern double sol_y[{m}];

/* Solver info (read by cpg_retrieve_info). OSQP-style residuals computed from
 * the canonical data and the returned solution:
 *   fom_pri_res = || Ax - clamp(Ax, l, u) ||_inf   (primal infeasibility)
 *   fom_dua_res = || P x + q + A^T y ||_inf         (dual infeasibility / KKT)
 * (fom_iter / fom_status come straight from the fomtools solver). */
extern double fom_obj_val;
extern int fom_iter;
extern int fom_status;
extern double fom_pri_res;
extern double fom_dua_res;

/* Refresh parameters from Canon_Params, solve, and publish the solution. */
extern void {fn}(void);

#ifdef __cplusplus
}}
#endif

#endif /* CPG_FOM_BRIDGE_H */
"""

    copies = []
    dims = _piece_dims(qp)
    if scaling is not None:
        # _param_copy_line indexes bridge_E by the Canon_Params offset.
        assert dims["b"][1] == 0 and dims["u_ineq"][1] == qp.n_eq, dims
        assert len(scaling.E) == qp.n_eq + qp.n_ineq == m, (len(scaling.E), m)
    for i, piece in enumerate(spec.param_copy):
        member, offset, length = dims[piece]
        src = f"{prefix}Canon_Params.{member}" + (f" + {offset}" if offset else "")
        line = _param_copy_line(piece, i, src, offset, scaling is not None)
        copies.append(f"  for (i = 0; i < {length}; i++) {{\n{line}\n  }}")
    copies_src = "\n".join(copies)

    if has_quad_term:
        quad_src = f"""\
  for (i = 0; i < {n}; i++) {{
    for (j = {prefix}Canon_Params.P->p[i]; j < {prefix}Canon_Params.P->p[i + 1]; j++) {{
      fom_obj_val += 0.5 * {prefix}Canon_Params.P->x[j] * sol_x[{prefix}Canon_Params.P->i[j]] * sol_x[i];
    }}
  }}
"""
    else:
        quad_src = "  /* no quadratic term */\n"

    settings_src = _settings_block(prefix, tuple(settings), schedule_len)
    if iter_count is None:
        iter_src = "  fom_iter = (int)fom_work.solution.iter;"
    else:
        iter_src = (
            f"  /* The body is the whole recorded run, executed once, so the loop\n"
            f"   * counter is 1; report the {iter_count} iterations it performs. */\n"
            f"  fom_iter = {iter_count};"
        )
    residual_src = _residual_block(qp, prefix, has_quad_term)
    # Scratch for the residual evaluation (statically allocated, like sol_x).
    scratch = (
        f"static double bridge_Ax[{max(m, 1)}];  /* A x, for the primal residual */\n"
        f"static double bridge_g[{n}];           /* P x + q + A^T y, the dual residual */"
    )
    if scaling is not None:
        scratch += "\n" + _scaling_block(scaling)
        x_out = f"bridge_D[i] * (double)fom_work.solution.x[{spec.primal_offset} + i]"
        y_out = f"bridge_E[i] * (double)fom_work.solution.x[{spec.dual_offset} + i] / bridge_c"
    else:
        x_out = f"(double)fom_work.solution.x[{spec.primal_offset} + i]"
        y_out = f"(double)fom_work.solution.x[{spec.dual_offset} + i]"

    source = f"""\
{_BANNER}
#include "cpg_fom_bridge.h"
#include "cpg_workspace.h"
#include "fom_solver.h"

double sol_x[{n}];
double sol_y[{m}];
double fom_obj_val;
int fom_iter;
int fom_status;
double fom_pri_res;
double fom_dua_res;

static FomWorkspace fom_work;
static int fom_initialized = 0;
{scratch}

void {fn}(void) {{
  FomParams fom_params;
  int i, j;
  if (!fom_initialized) {{
    FomSettings fom_settings;
    fom_set_default_settings(&fom_settings);
    fom_setup(&fom_work, &fom_settings);
    fom_initialized = 1;
  }}

{settings_src}

  /* Canonical parameter vectors -> FomParams (field order = p0, p1, ...). */
{copies_src}
  fom_update_params(&fom_work, &fom_params);

  fom_status = (int)fom_solve(&fom_work);

  for (i = 0; i < {n}; i++) {{
    sol_x[i] = {x_out};
  }}
  for (i = 0; i < {m}; i++) {{
    sol_y[i] = {y_out};
  }}
{iter_src}

  /* OSQP-style primal/dual residuals from the canonical data + the solution. */
{residual_src}
  (void)j;

  /* Objective 0.5 x'Px + q'x; cvxpygen's retrieve_info adds the constant d
   * and flips the sign for maximization problems. */
  fom_obj_val = 0.0;
{quad_src}\
  for (i = 0; i < {n}; i++) {{
    fom_obj_val += {prefix}Canon_Params.q[i] * sol_x[i];
  }}
}}
"""

    (solver_code_dir / "include").mkdir(parents=True, exist_ok=True)
    (solver_code_dir / "src").mkdir(parents=True, exist_ok=True)
    (solver_code_dir / "include" / "cpg_fom_bridge.h").write_text(header)
    (solver_code_dir / "src" / "cpg_fom_bridge.c").write_text(source)


def write_solver_cmake_stub(solver_code_dir: str | Path) -> None:
    """Create ``solver_code/CMakeLists.txt`` for cvxpygen's writer to append to.

    The writer appends ``file(GLOB SOLVER_SRC ...)`` blocks built from the
    interface's ``cmake_sources``/``cmake_headers`` and exports them to the
    parent scope, so the stub itself carries no build logic.
    """
    path = Path(solver_code_dir) / "CMakeLists.txt"
    path.write_text("# fomtools solver sources — populated by CVXPYgen (write_canon_cmake)\n")
