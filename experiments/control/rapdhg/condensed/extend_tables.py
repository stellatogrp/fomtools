"""Lengthen the schedule tables of both generated solvers without an agent.

The solvers are generated at a short table because the generated benchmark runs
five thousand solves at the table's length and the optimization phase runs that
benchmark after every change.  Afterwards the length is free to raise: the
agent's ``src/fom_solver.c`` reads ``FOM_MAX_ITER`` and the ``fom_sched_*``
accessors rather than any literal, and everything else in the directory is
deterministic and regenerated by ``scaffold``, which by contract never writes
the solver source.  So this re-scaffolds both directories at
``condensed.study.MAX_ITERS``, rebuilds, runs ``make verify`` at that length,
and checks each solver against the NumPy controller again.

    python -m condensed.extend_tables
    python -m condensed.extend_tables --max-iters 8192
"""

from __future__ import annotations

import argparse

from fomtools.codegen.emit import scaffold
from fomtools.codegen.harness import build_and_verify

from common import codegen_driver
from common import study as pipeline
from common.csolver import CSolver
from condensed.study import MAX_ITERS, build


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-iters", type=int, default=MAX_ITERS)
    args = parser.parse_args()

    study = build(max_iters=args.max_iters)
    config = codegen_driver.config_for(args.max_iters, study.tol_verify)
    ir = codegen_driver.extract(study.recording, study.boxes, config=config, name=f"mpc_{study.name}")

    failures = []
    for label, directory in (("emitted C", study.emitted), ("optimized C", study.optimized)):
        if not (directory / "src" / "fom_solver.c").exists():
            print(f"skipping {label}: nothing generated in {directory}")
            continue
        solver_src = (directory / "src" / "fom_solver.c").read_text()
        target = scaffold(ir, directory, config)
        assert (directory / "src" / "fom_solver.c").read_text() == solver_src, "scaffold touched the solver"
        result = build_and_verify(directory, target)
        print(f"{label}: tables extended to {args.max_iters}; make verify "
              f"{'passed' if result.success else 'FAILED'}")
        if not result.success:
            failures.append(label)
            print(result.output[-2000:])
            continue
        err = pipeline.check_equivalence(study, CSolver(directory), label, verbose=False)
        print(f"  agrees with the NumPy controller to {err:.3e}")
        if err > pipeline.TOL:
            failures.append(label)

    if failures:
        raise SystemExit("FAILED: " + ", ".join(failures))
    print("\nOK: both solvers verify at the extended table length.")


if __name__ == "__main__":
    main()
