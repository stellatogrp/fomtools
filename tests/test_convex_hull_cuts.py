"""
Tests for the root-node convex hull cuts of ReLU and saturated linear steps.

1. The separation routines match the corrected Theorems 1 and 3: every returned cut
   is valid on the box, and whenever the relaxed point lies above the concave
   envelope (or below the convex envelope) by more than the formulation's own rows
   allow, the most violated cut is tight at that point.
2. In a vp, the cuts are valid for the actual step graphs, including argument
   constants and arguments spanning several leaves.
3. Cuts never change the MIP optimum, persist across solves (sequential ``K``),
   respect ``cut_rounds``, and reach the OBBT LP with one tightening pass per round.
"""

import itertools

import numpy as np
import pytest
from scipy.optimize import linprog

import fomtools.solvers.mip_solver as mip_solver
from fomtools.utils.convex_hull_cuts import separate_relu, separate_satlin, separate_soft_threshold
from fomtools.verifier import Verifier

MIP_EXACT = {"OutputFlag": 0, "MIPGap": 1e-9}


# --------------------------------------------------------------------------
# Brute-force envelopes of y -> f(a^T y + k) over a box.
# --------------------------------------------------------------------------


def _cell_vertices(a, k, L, U, breakpoints):
    """Box vertices plus the points where box edges cross ``a^T y + k = t``.

    ``f`` is affine on every cell of the box cut by these hyperplanes, so both
    envelopes are generated by the cells' vertices, which are all in this set.
    """
    d = len(a)
    corners = [np.array(v, dtype=float) for v in itertools.product(*zip(L, U))]
    points = list(corners)
    for v in corners:
        for j in range(d):
            if v[j] != L[j] or a[j] == 0:
                continue
            w = v.copy()
            w[j] = U[j]
            for t in breakpoints:
                s = (t - k - a @ v) / (a @ (w - v))
                if 0 < s < 1:
                    points.append(v + s * (w - v))
    return np.array(points)


def _envelope(f, points, y, sense):
    """Concave (``sense=1``) or convex (``sense=-1``) envelope of ``f`` at ``y``."""
    vals = np.array([f(p) for p in points])
    A_eq = np.vstack([points.T, np.ones(len(points))])
    res = linprog(-sense * vals, A_eq=A_eq, b_eq=np.append(y, 1.0), bounds=(0, None))
    assert res.status == 0
    return sense * -res.fun


def _random_unstable(rng, d, k, lo, hi):
    """Random ``a`` and box such that ``a^T y + k`` ranges over an interval containing ``[lo, hi]``."""
    while True:
        a = rng.normal(size=d)
        L = rng.uniform(-1.5, 0.0, size=d)
        U = L + rng.uniform(0.3, 2.0, size=d)
        tmin = k + np.minimum(a * L, a * U).sum()
        tmax = k + np.maximum(a * L, a * U).sum()
        if tmin < lo and tmax > hi:
            return a, L, U


def _check_cut_valid(cut, f, a, k, L, U, rng, n=20000):
    Y = rng.uniform(L, U, size=(n, len(a)))
    W = f(Y @ a + k)
    assert np.all(cut.sense * (W - (Y @ cut.alpha + cut.beta)) <= 1e-9)


@pytest.mark.parametrize("k", [0.0, 0.7, -0.4])
def test_relu_separation_matches_hull(k):
    rng = np.random.default_rng(0)

    def relu(t):
        return np.maximum(t, 0.0)

    n_checked = 0
    for _ in range(40):
        a, L, U = _random_unstable(rng, 3, k, 0.0, 0.0)
        points = _cell_vertices(a, k, L, U, [0.0])
        y = rng.uniform(L, U)
        env = _envelope(lambda p: relu(a @ p + k), points, y, 1)
        # Strictly above the concave envelope: a cut must be found and be tight at y.
        cut = separate_relu(a, k, L, U, y, env + 1e-3)
        assert cut is not None and cut.sense == 1
        assert abs((cut.alpha @ y + cut.beta) - env) <= 1e-6
        _check_cut_valid(cut, relu, a, k, L, U, rng)
        # On or below the envelope: nothing is violated.
        assert separate_relu(a, k, L, U, y, env - 1e-4) is None
        n_checked += 1
    assert n_checked == 40


@pytest.mark.parametrize("k", [0.0, 0.5])
@pytest.mark.parametrize("case", ["both", "lower_only", "upper_only"])
def test_satlin_separation_matches_hull(case, k):
    rng = np.random.default_rng(1)
    b, c = -0.3, 0.4

    def sat(t):
        return np.clip(t, b, c)

    lo, hi = {"both": (b, c), "lower_only": (b, b), "upper_only": (c, c)}[case]
    found = {1: 0, -1: 0}
    for _ in range(40):
        a, L, U = _random_unstable(rng, 3, k, lo, hi)
        tmin = k + np.minimum(a * L, a * U).sum()
        tmax = k + np.maximum(a * L, a * U).sum()
        if case == "lower_only" and tmax > c:
            continue
        if case == "upper_only" and tmin < b:
            continue
        points = _cell_vertices(a, k, L, U, [b, c])
        y = rng.uniform(L, U)
        theta = a @ y + k
        for sense in (1, -1):
            env = _envelope(lambda p: sat(a @ p + k), points, y, sense)
            # Rows already in the formulation: b <= w <= c, and w <= theta if
            # tmin >= b, w >= theta if tmax <= c. Only beyond them is a cut expected.
            if sense == 1:
                base = min(c, theta) if tmin >= b else c
            else:
                base = max(b, theta) if tmax <= c else b
            w_out = env + sense * 1e-3
            cut = separate_satlin(a, k, L, U, y, w_out, b, c)
            if sense * (base - env) > 1e-6:
                # Detection, not depth: see test_soft_threshold_separation_matches_hull.
                assert cut is not None and cut.sense == sense
                found[sense] += 1
            if cut is not None:
                _check_cut_valid(cut, sat, a, k, L, U, rng)
            assert separate_satlin(a, k, L, U, y, env - sense * 1e-4, b, c) is None
    # One-sided cases only produce cuts on the saturating side.
    if case in ("both", "lower_only"):
        assert found[1] > 0
    if case in ("both", "upper_only"):
        assert found[-1] > 0


def _soft(t, lambd):
    return np.sign(t) * np.maximum(np.abs(t) - lambd, 0.0)


@pytest.mark.parametrize("k", [0.0, 0.2])
@pytest.mark.parametrize("case", ["both", "right_only", "left_only"])
def test_soft_threshold_separation_matches_hull(case, k):
    """Every line of Q is in the separator, so any point outside the hull is detected."""
    rng = np.random.default_rng(2)
    lambd = 0.3

    def soft(t):
        return _soft(t, lambd)

    lo, hi = {"both": (-lambd, lambd), "right_only": (lambd, lambd), "left_only": (-lambd, -lambd)}[
        case
    ]
    n_checked = 0
    for _ in range(5000):
        if n_checked == 25:
            break
        a, L, U = _random_unstable(rng, 3, k, lo, hi)
        tmin = k + np.minimum(a * L, a * U).sum()
        tmax = k + np.maximum(a * L, a * U).sum()
        if case == "right_only" and tmin < -lambd:
            continue
        if case == "left_only" and tmax > lambd:
            continue
        points = _cell_vertices(a, k, L, U, [-lambd, lambd])
        y = rng.uniform(L, U)
        envs = {sense: _envelope(lambda p: soft(a @ p + k), points, y, sense) for sense in (1, -1)}
        # A point strictly between the envelopes is inside the hull.
        inside = 0.5 * (envs[1] + envs[-1])
        assert separate_soft_threshold(a, k, L, U, y, inside, lambd) is None
        for sense, env in envs.items():
            cut = separate_soft_threshold(a, k, L, U, y, env + sense * 1e-3, lambd)
            # Separation detects every point outside the hull (corrected Prop. 2), but
            # the returned cut need not be the deepest: when I* is inadmissible the
            # subset family defers to the pair family.
            assert cut is not None and cut.sense == sense
            assert sense * (cut.alpha @ y + cut.beta) >= sense * env - 1e-9
            _check_cut_valid(cut, soft, a, k, L, U, rng)
        n_checked += 1
    assert n_checked == 25


# --------------------------------------------------------------------------
# Cuts generated inside a VP are valid for the actual step graphs.
# --------------------------------------------------------------------------


@pytest.fixture
def record_cuts(monkeypatch):
    """Record ``(leaves, a, k, cut)`` for every cut the MIP solver separates."""
    records = []
    original = mip_solver._cut_to_constraint

    def recording(cut, w_expr, leaves):
        ((w_leaf, coeff),) = w_expr.decomposition_dict.items()
        pos = int(
            np.argmax(np.abs(np.asarray(coeff.todense() if hasattr(coeff, "todense") else coeff)))
        )
        records.append((list(leaves), w_leaf, pos, cut))
        return original(cut, w_expr, leaves)

    monkeypatch.setattr(mip_solver, "_cut_to_constraint", recording)
    return records


def _pgd_chain(kind, K, *, const, obbt=None, seed=3, n=3):
    """Projected gradient on a box/orthant QP with a parametric linear term."""
    rng = np.random.default_rng(seed)
    M = rng.normal(size=(n, n))
    P = M @ M.T / n + 0.1 * np.eye(n)
    t = 0.5 / np.linalg.norm(P, 2)
    l, u = -0.3 * np.ones(n), 0.4 * np.ones(n)
    lambd = 0.05
    vp = Verifier(method="mip", solver="gurobi", obbt_solver=obbt, params=MIP_EXACT)
    q = vp.parameter(n, lb=-np.ones(n), ub=np.ones(n))
    z = [vp.iterate(n, lb=np.zeros(n), ub=np.zeros(n))]
    for _ in range(K):
        arg = z[-1] - t * (P @ z[-1] + q) + const
        if kind == "relu":
            z.append(vp.relu(arg))
        elif kind == "satlin":
            z.append(vp.satlin(arg, l=l, u=u))
        else:
            z.append(vp.soft_threshold(arg, lambd=lambd))

    def simulate(Q):
        Z = [np.zeros_like(Q)]
        for _ in range(K):
            arg = Z[-1] - t * (Z[-1] @ P.T + Q) + const
            if kind == "relu":
                Z.append(np.maximum(arg, 0))
            elif kind == "satlin":
                Z.append(np.clip(arg, l, u))
            else:
                Z.append(_soft(arg, lambd))
        return Z

    return vp, q, z, simulate


@pytest.mark.parametrize("kind", ["relu", "satlin", "soft"])
@pytest.mark.parametrize("const", [0.1, -0.15])
def test_vp_cuts_valid_on_trajectories(kind, const, record_cuts):
    K = 3
    # Seed chosen so that both constants produce cuts for both step types.
    vp, q, z, simulate = _pgd_chain(kind, K, const=const, seed=5)
    for k in range(1, K + 1):
        vp.set_objective_norm(z[k] - z[k - 1], np.inf)
        vp.solve(convex_hull_cuts=True, cut_rounds=2)
    assert record_cuts, "expected at least one cut"

    Q = np.random.default_rng(0).uniform(-1, 1, size=(20000, len(q.lb)))
    Z = simulate(Q)
    values = {id(q): Q, **{id(zk): Zk for zk, Zk in zip(z, Z)}}
    # Each cut bounds one output row of some z[k]; check it on every sample.
    for leaves, w_leaf, pos, cut in record_cuts:
        Y = np.hstack([values[id(leaf)] for leaf in leaves])
        w = values[id(w_leaf)][:, pos]
        assert np.all(cut.sense * (w - (Y @ cut.alpha + cut.beta)) <= 1e-7)


@pytest.mark.parametrize("kind", ["relu", "satlin", "soft"])
@pytest.mark.parametrize("obbt", [None, "gurobi"])
def test_cuts_preserve_mip_optimum(kind, obbt):
    K = 4
    vp_no, _, z_no, _ = _pgd_chain(kind, K, const=0.1, obbt=obbt)
    vp_cut, _, z_cut, _ = _pgd_chain(kind, K, const=0.1, obbt=obbt)
    for k in range(1, K + 1):
        vp_no.set_objective_norm(z_no[k] - z_no[k - 1], np.inf)
        vp_cut.set_objective_norm(z_cut[k] - z_cut[k - 1], np.inf)
        # The encoding lets q exceed |r_j| by up to M * IntFeasTol, so incumbents can
        # differ at the 1e-6 level between otherwise identical solves.
        assert vp_cut.solve(convex_hull_cuts=True, cut_rounds=2) == pytest.approx(
            vp_no.solve(), abs=1e-5
        )


# --------------------------------------------------------------------------
# Persistence across solves, rounds, and OBBT.
# --------------------------------------------------------------------------


def _num_constrs(vp):
    vp.canonicalizer.solver.model.update()
    return vp.canonicalizer.solver.model.NumConstrs


def test_cuts_persist_across_K():
    K = 3
    vp, _, z, _ = _pgd_chain("satlin", K, const=0.0)
    total_cuts = 0
    for k in range(1, K + 1):
        vp.set_objective_norm(z[k] - z[k - 1], np.inf)
        before = _num_constrs(vp)
        vp.solve(convex_hull_cuts=True)
        added = sum(s["cuts"] for s in vp.cut_stats)
        total_cuts += added
        # The base model keeps every cut, so the next K builds on top of them.
        assert _num_constrs(vp) == before + added
    assert total_cuts > 0


def test_cut_rounds():
    K = 3
    counts = {}
    for rounds in (1, 3):
        vp, _, z, _ = _pgd_chain("satlin", K, const=0.0)
        n = 0
        for k in range(1, K + 1):
            vp.set_objective_norm(z[k] - z[k - 1], np.inf)
            vp.solve(convex_hull_cuts=True, cut_rounds=rounds)
            assert len(vp.cut_stats) <= rounds
            n += sum(s["cuts"] for s in vp.cut_stats)
        counts[rounds] = n
    assert counts[3] >= counts[1]


def test_cuts_reach_obbt_with_one_pass_per_round(monkeypatch):
    K = 3
    vp, _, z, _ = _pgd_chain("satlin", K, const=0.0, obbt="gurobi")
    passes = []
    original = vp._tighten_leaf_bounds

    def counting(leaves):
        leaves = list(leaves)
        passes.append(len(leaves))
        return original(leaves)

    for k in range(1, K + 1):
        vp.set_objective_norm(z[k] - z[k - 1], np.inf)
        obbt_model = vp.obbt_handler.solver.model
        obbt_model.update()
        before = obbt_model.NumConstrs
        widths_before = [np.asarray(zk.ub) - np.asarray(zk.lb) for zk in z]
        monkeypatch.setattr(vp, "_tighten_leaf_bounds", counting)
        passes.clear()
        vp.solve(convex_hull_cuts=True, cut_rounds=2)
        obbt_model.update()
        added = sum(s["cuts"] for s in vp.cut_stats)
        assert obbt_model.NumConstrs == before + added
        assert len(passes) == len(vp.cut_stats)
        for zk, w in zip(z, widths_before):
            assert np.all(np.asarray(zk.ub) - np.asarray(zk.lb) <= w + 1e-9)


def test_portfolio_like_steps_do_not_crash():
    """Affine (implicit linear) steps are skipped instead of raising."""
    n = 3
    vp = Verifier(method="mip", solver="gurobi", obbt_solver="gurobi", params=MIP_EXACT)
    x = vp.parameter(n, lb=np.zeros(n), ub=0.6 * np.ones(n))
    y0 = vp.iterate(n, lb=np.zeros(n), ub=np.zeros(n))
    y1 = vp.implicit_linear(y0 + x, output_mat=2.0 * np.eye(n))
    w = vp.satlin(y1 - 0.1, l=np.zeros(n), u=0.25 * np.ones(n))
    s = x - vp.relu(x - w)
    vp.set_objective_norm(s - y0, np.inf)
    assert vp.solve(convex_hull_cuts=True) == pytest.approx(vp.solve(), abs=1e-6)
